#!/usr/bin/env python3
"""Merge the Lichess chess-openings TSV files into C++ data.

The upstream database (https://github.com/lichess-org/chess-openings) is
released under CC0-1.0, so it can be redistributed inside the WeChess binary.
This script is only needed when the database is refreshed; the generated
`cpp/data/openings_book.inc` is committed so builds need no Python.

Usage: python3 scripts/build_openings.py [data-dir]
"""

import glob
import os
import sys

OPEN = 'R"WECHESS_OPENINGS('
CLOSE = ')WECHESS_OPENINGS"'


def main() -> int:
    data_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join("cpp", "data")
    files = sorted(glob.glob(os.path.join(data_dir, "openings_*.tsv")))
    if not files:
        print("no openings_*.tsv files found in %s" % data_dir, file=sys.stderr)
        return 1

    rows = []
    for path in files:
        with open(path, encoding="utf-8") as handle:
            header = handle.readline().rstrip("\n").split("\t")
            try:
                eco_i = header.index("eco")
                name_i = header.index("name")
                pgn_i = header.index("pgn")
            except ValueError:
                print("unexpected header in %s: %s" % (path, header), file=sys.stderr)
                return 1
            for line in handle:
                parts = line.rstrip("\n").split("\t")
                if len(parts) <= max(eco_i, name_i, pgn_i):
                    continue
                eco, name, pgn = parts[eco_i], parts[name_i], parts[pgn_i]
                if not eco or not name or not pgn:
                    continue
                if OPEN in name or CLOSE in name:
                    print("skipping name containing the raw-string delimiter: %s" % name, file=sys.stderr)
                    continue
                rows.append((eco, name, pgn))

    rows.sort(key=lambda row: (row[0], row[1]))
    out_path = os.path.join(data_dir, "openings_book.inc")
    with open(out_path, "w", encoding="utf-8") as out:
        out.write("// Generated by scripts/build_openings.py -- do not edit.\n")
        out.write("// Source: https://github.com/lichess-org/chess-openings (CC0-1.0)\n")
        out.write("// Format: ECO<TAB>Name<TAB>PGN moves\n")
        out.write("namespace wechess {\nnamespace data {\ninline constexpr const char* kOpeningsTsv = %s\n" % OPEN)
        for eco, name, pgn in rows:
            out.write("%s\t%s\t%s\n" % (eco, name, pgn))
        out.write("%s;\n}  // namespace data\n}  // namespace wechess\n" % CLOSE)

    print("wrote %s (%d openings)" % (out_path, len(rows)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
